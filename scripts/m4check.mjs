import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const out = process.argv[2];
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const logs = [];
page.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto('http://localhost:4173/?seed=lantern&play&q=low&hour=8', { waitUntil: 'load' });
await page.waitForTimeout(2500);
await page.evaluate(() => { const g = window.__game; g.stop(); g.simulate(3, 10); });
for (let i = 0; i < 25; i++) { const n = await page.evaluate(() => { const g = window.__game; g.tick(1/30, false); return g.streamer.tilesPending; }); if (n === 0) break; await page.waitForTimeout(300); }
const animals = await page.evaluate(() => { const g = window.__game; g.simulate(2, 10); return [...g.animals.active.values()].map((a) => a.def.id + '@' + a.obj.position.distanceTo(g.car.pos).toFixed(0)); });
console.log('animals', animals.join(' '));
// walk out and stage a deer in front of the camera
const aim = await page.evaluate(() => {
  const g = window.__game;
  g.exitCar();
  const w = g.walker;
  const fx = -Math.sin(w.yaw), fz = -Math.cos(w.yaw);
  const x = w.pos.x + fx * 11 + Math.cos(w.yaw) * 2.5, z = w.pos.z + fz * 11 - Math.sin(w.yaw) * 2.5;
  const { SUBJECT_BY_ID } = window.__subjects;
  g.animals.spawn('deer:test', SUBJECT_BY_ID.deer, new (g.camera.position.constructor)(x, 0, z), 0);
  const a = g.animals.active.get('deer:test'); a.timer = 99;
  w.pitch = -0.05;
  for (let i = 0; i < 3; i++) g.tick(1/30, false);
  return 'deer';
});
console.log('aim at', aim);
await page.keyboard.down('KeyQ');
const frame = await page.evaluate(() => { const g = window.__game; for (let i = 0; i < 20; i++) g.tick(1/30, i === 19); return g.renderer.domElement.toDataURL('image/png'); });
(await import('node:fs')).writeFileSync(out + '/viewfinder.png', Buffer.from(frame.split(',')[1], 'base64'));
await page.evaluate(async () => { await window.__game.photo.shoot(); });
await page.keyboard.up('KeyQ');
await page.evaluate(() => { const g = window.__game; for (let i = 0; i < 3; i++) g.tick(1/30, false); });
// shoot an empty sky too
await page.evaluate(async () => { const g = window.__game; g.walker.pitch = 1.2; g.tick(1/30, false); g.photo.raised = true; await g.photo.shoot(); g.photo.raised = false; });
const pend = await page.evaluate(() => window.__game.photo.pending);
console.log('pending', pend, 'shots', await page.evaluate(() => window.__game.player.shots));
// develop
await page.evaluate(() => { const g = window.__game; const site = g.stops.nearbySites(0, 1000).find((s) => s.kind === 'gas'); window.__app.photoUI.kiosk(site); });
await page.waitForTimeout(800);
await page.click('#btn-develop');
await page.waitForTimeout(600);
await page.evaluate(() => window.__game.tick(1/60, true));
await page.screenshot({ path: out + '/develop.png', timeout: 60000 });
await page.click('#btn-next');
await page.waitForTimeout(400);
await page.click('#btn-next');
await page.waitForTimeout(400);
console.log('after develop', await page.evaluate(() => { const g = window.__game; return { money: g.player.money, journal: Object.keys(g.journal.d.entries) }; }));
await page.click('#panel-close');
await page.evaluate(() => window.__app.photoUI.journal());
await page.waitForTimeout(800);
await page.screenshot({ path: out + '/journal.png', timeout: 60000 });
await page.click('#panel-close');
await page.evaluate(() => window.__app.photoUI.gallery());
await page.waitForTimeout(800);
await page.screenshot({ path: out + '/gallery.png', timeout: 60000 });
console.log(logs.filter((l) => !l.includes('GPU stall') && !l.includes('WebGL')).slice(0, 20).join('\n'));
await browser.close();
