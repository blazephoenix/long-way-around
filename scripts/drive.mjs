import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 640, height: 360 } });
page.on('pageerror', (e) => console.log(`[pageerror] ${e.message}`));
await page.goto('http://localhost:4173/?seed=lantern&play&q=low', { waitUntil: 'load' });
await page.waitForTimeout(3000);
const st = () => page.evaluate(() => { const g = window.__game; return { kmh: g.car.kmh.toFixed(1), yaw: g.car.yaw.toFixed(2), cruise: g.car.cruise, fuel: g.car.fuel.toFixed(4), surf: g.car.surface, x: g.car.pos.x.toFixed(1), z: g.car.pos.z.toFixed(1) }; });
await page.evaluate(() => window.__game.stop());
await page.keyboard.down('KeyW');
await page.evaluate(() => window.__game.simulate(8));
console.log('after 8s throttle', await st());
await page.keyboard.up('KeyW');
await page.keyboard.press('KeyC');
await page.evaluate(() => window.__game.tick(1/30, false));
await page.evaluate(() => window.__game.simulate(5));
console.log('cruise 5s', await st());
await page.keyboard.down('KeyD');
await page.evaluate(() => window.__game.simulate(1.5));
await page.keyboard.up('KeyD');
console.log('steer right 1.5s', await st());
await page.keyboard.down('KeyS');
await page.evaluate(() => window.__game.simulate(6));
console.log('brake 6s', await st());
await page.evaluate(() => window.__game.simulate(3));
console.log('reverse 3s more', await st());
await page.keyboard.up('KeyS');
await browser.close();
