import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 640, height: 360 } });
await page.goto('http://localhost:4173/?seed=lantern&play&q=low', { waitUntil: 'load' });
await page.waitForTimeout(2500);
await page.evaluate(() => window.__game.stop());
await page.keyboard.down('KeyW');
await page.evaluate(() => window.__game.simulate(2));
await page.keyboard.up('KeyW');
await page.keyboard.down('KeyS');
await page.evaluate(() => { const g = window.__game; while (g.car.speed > 2.2) g.tick(1/30, false); });
await page.keyboard.up('KeyS');
const before = await page.evaluate(() => { const g = window.__game; g.exitCar(); return [g.mode, g.car.pos.x, g.car.pos.z, g.car.speed]; });
await page.evaluate(() => window.__game.simulate(30));
const after = await page.evaluate(() => { const g = window.__game; return [g.car.pos.x, g.car.pos.z, g.car.speed]; });
console.log('exit at speed', before[3].toFixed(2), 'mode', before[0], 'moved over 30 s:', Math.hypot(after[0] - before[1], after[1] - before[2]).toFixed(2), 'm, speed now', after[2].toFixed(3));
await browser.close();
